/**
 * data/golfer.js — the one golfer, assembled from the site that owns him.
 *
 * ---------------------------------------------------------------------------
 * THIS FILE USED TO BE A WRITABLE STORE. IT IS NOW A READER.
 * ---------------------------------------------------------------------------
 * There was a localStorage record here, an editable field whitelist, and a form
 * at #/edit that wrote to it. All of it is gone, because all of it was a second
 * copy of facts that LukeThomasSelzer.com already publishes.
 *
 * A second copy of a fact is not a backup, it is a future disagreement. The
 * editor could not push to the real site -- it wrote to the reviewer's own
 * browser -- so every save quietly widened the gap between what this app
 * believed and what a coach would actually see. The fix is not a sync button.
 * The fix is to stop holding an opinion: read the site, render the site.
 *
 * ---------------------------------------------------------------------------
 * WHERE EACH FIELD COMES FROM, AND WHY THEY DIFFER
 * ---------------------------------------------------------------------------
 *   identity      LIVE. Fetched per page load from /api/personal, which is
 *                 public and CORS-enabled. See data/live.js.
 *
 *   scoringAvg    PUBLISHED by the site and generated into luke-season.js.
 *                 lib/trend.js independently recomputes it from the rounds and
 *                 a test asserts the two agree, so the site disagreeing with
 *                 itself becomes a failing test rather than a wrong answer.
 *
 *   rounds        GENERATED by _ref/gen_luke.py from the live page.
 *   ranks         GENERATED the same way. Snapshots rather than live reads
 *                 because the page HTML carries PORTFOLIO_DATA but is served
 *                 WITHOUT CORS headers, so a browser on another origin cannot
 *                 fetch it. Until the site exposes these -- a few lines in its
 *                 netlify.toml, or a small /api/stats function -- regenerating
 *                 is the honest ceiling, and #/data labels it as such.
 *
 * NOTHING in this file is a number somebody typed. That is the whole point:
 * hand-copied stats rot in silence, because the person who would notice is
 * looking at the website, not at this repo.
 *
 *   gpa / sat     ABSENT, on purpose. Luke is 13. The Fit engine drops missing
 *                 academic inputs rather than scoring them as zero.
 */

import { lukeSeason, lukePublished } from "./luke-season.js";

/**
 * Values transcribed from the live site that this app cannot yet fetch.
 *
 * Everything here is REAL and sourced -- nothing is invented. The identity
 * fields are seeded from /api/personal so the first paint has something true to
 * show before the live fetch resolves, then live values replace them.
 */
export const GOLFER_SNAPSHOT = Object.freeze({
  id: "luke",

  // Identity: minimal, and only so the first paint has something true on screen
  // before the live read resolves. Anything the site answers for is replaced.
  name: "Luke Thomas Selzer",
  hometown: "Charlotte, NC",
  class_year: "Class of 2031",
  age: "13",

  // Every published stat, generated from the live page. Spread rather than
  // relisted, so adding a stat upstream needs no edit here.
  ...lukePublished,

  tournaments: lukeSeason,
});

/**
 * The golfer, ready to score: published stats with live identity laid on top.
 *
 * @param {Object} [live] normalised response from data/live.js
 */
export const buildGolfer = (live = {}) => ({ ...GOLFER_SNAPSHOT, ...live });
